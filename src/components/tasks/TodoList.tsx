"use client";

import { useState, useTransition } from "react";
import { PlusCircle, XCircle } from "lucide-react";
import { NewTodo, Todo } from "@/types/todoTypes";
import TodoForm from "./TodoForm";
import TodoCard from "./TodoCard";

import {
  addTask,
  updateTaskTime,
  editTask,
  deleteTask,
} from "@/actions/taskAction";

interface TodoListProps {
  //to load the initial list of todos fetched via server component parent or even pass initial todos manually
  initialTodos?: Todo[];
}

// later user uuid for generating id
const generateTempId = (): string => {
  return `temp-${Date.now()}-${Math.random().toString(36).substring(2, 9)}`;
};

export function TodoList({ initialTodos = [] }: TodoListProps) {
  const [todos, setTodos] = useState<Todo[]>(initialTodos); //'todos' hold the array of tasks currently displayed in the UI
  const [isAddingTodo, setIsAddingTodo] = useState(false); // boolean to control the visibility of the TodoForm
  // Use useTransition for non-critical state updates during server actions
  const [isPending, startTransition] = useTransition(); //
  const [updatingTodoId, setUpdatingTodoId] = useState<string | null>(null);
  const [deletingTodoId, setDeletingTodoId] = useState<string | null>(null);
  // Keep track of submission state for the form specifically
  const [isSubmittingForm, setIsSubmittingForm] = useState(false);

  // -----async todo addition and ui update
  const handleAddTodo = async (newTodoData: NewTodo) => {
    setIsSubmittingForm(true); // Indicate form submission start and disable input /buttons while submittin
    const tempId = generateTempId();

    // 1. Optimistic UI update
    //create a temporary 'Todo' object based on the form data and the temp id and assume default values for fields generated by server/db i.e data duration , timestamp
    const optimisticTodo: Todo = {
      id: tempId, // Use temporary ID for the key
      ...newTodoData,
      date: new Date().toISOString(),
      duration: 0,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
    //immediately update the local 'todo's state to include the optimistic todo update
    // so that the ui updates instantly before the server responds
    setTodos((prev) => [optimisticTodo, ...prev]);
    setIsAddingTodo(false); // Close the form

    // now we will call the server action fn 'addTask' with the form data
    startTransition(async () => {
      try {
        //  Call server action
        const result = await addTask(newTodoData);

        // 3. Handle server action result
        if (result.success && result.newTask) {
          // if the server action was successful and returned the real task data, then
          //update the 'todos' state again , replacing the temporary task with the actual task data from the server with the server real id
          setTodos((prev) =>
            prev.map((t) => (t.id === tempId ? result.newTask! : t))
          );
        } else {
          //if the server action failed
          console.error("Failed to add todo:", result.error);
          // Remove the optimistic ui added task using the tempID
          setTodos((prev) => prev.filter((t) => t.id !== tempId));
          setIsAddingTodo(true); // Optional: reopen form on error
          // TODO: Show user-friendly error notification i.e show toast on failure or success both
        }
      } catch (error) {
        console.error("Error calling addTask:", error);
        // Revert optimistic update on unexpected error
        setTodos((prev) => prev.filter((t) => t.id !== tempId));
        setIsAddingTodo(true); // Optional: reopen form on error
        // TODO: Show user-friendly error notification
      } finally {
        setIsSubmittingForm(false); // close the form regardless of the error or success
      }
    });
  };
  // -------------------Event handling of Updating the Time duration for a task, triggered from TodoCard
  const handleUpdateTime = async (todoId: string, minutes: number) => {
    const originalTodos = todos; // Store original state for potential revert
    setUpdatingTodoId(todoId); // Set loading state for this specific card data being updated

    // 1. Optimistic UI update
    //update the local 'todos' state find the relevant todo by ID and update it's duration and 'updatedAt' fileds
    setTodos((prev) =>
      prev.map((todo) =>
        todo.id === todoId
          ? { ...todo, duration: minutes, updatedAt: new Date().toISOString() } // [cite: 71]
          : todo
      )
    );

    // ---calling server action and useTransition
    startTransition(async () => {
      try {
        // 2. call the 'updateTaskTime' server action
        const result = await updateTaskTime(todoId, minutes);

        // 3. Handle response from server action
        if (!result.success) {
          console.error("Failed to update todo time:", result.error);
          // if the server update failed, revert the local state to the original state
          setTodos(originalTodos);
          // TODO: Show user-friendly error notification
        }
        // On success, the optimistic update is already applied
      } catch (error) {
        console.error("Error calling updateTaskTime:", error);
        // Revert optimistic update on unexpected error
        setTodos(originalTodos);
        // TODO: Show user-friendly error notification
      } finally {
        setUpdatingTodoId(null); // Clear loading state for the card
      }
    });
  };
  // ------------Event handling of the Saving Edited card
  const handleEditTodo = async (
    todoId: string,
    updatedFields: Partial<Omit<Todo, "id" | "createdAt" | "date" | "duration">>
    //using Partial<..> to indicate that only some fields might be provided for update
    //and omit prevents trying to update immutable fields like 'id'
  ) => {
    const originalTodos = todos; // saving original state for pontential revert
    setUpdatingTodoId(todoId); // Using this setUpdatingTodoId fn to disable button on card

    // 1. Optimistic UI update to immediately updating the local state with the edited fields
    setTodos((prev) =>
      prev.map((todo) =>
        todo.id === todoId
          ? { ...todo, ...updatedFields, updatedAt: new Date().toISOString() } // [cite: 76]
          : todo
      )
    );

    // Prepare data payload for the editTask server action , and also to ensure only allowed data fields are send
    const dataToSend = {
      title: updatedFields.title || "", // Assuming title is always part of the update
      description:
        updatedFields.description !== undefined
          ? updatedFields.description
          : null, // to handle potential undefined field or empty
      tag: updatedFields.tag !== undefined ? updatedFields.tag : null,
    };

    // Basic client-side validation (mirroring server action) before calling server action
    if (!dataToSend.title.trim()) {
      console.error("Title cannot be empty.");
      setTodos(originalTodos); // Revert
      setUpdatingTodoId(null); //clear loading state
      // TODO: Show validation error in the edit form itself (TodoCard)
      return;
    }

    //callling server action and useTransistion
    startTransition(async () => {
      try {
        // call editTask server action
        const result = await editTask(todoId, dataToSend);

        // 3. Handle response from editTask server action
        if (!result.success) {
          console.error("Failed to edit todo:", result.error);
          // Revert optimistic update on failure
          setTodos(originalTodos);
          // TODO: Show user-friendly error notification
        }
        // On success, the optimistic update is already applied
      } catch (error) {
        console.error("Error calling editTask:", error);
        // Revert optimistic update on unexpected error
        setTodos(originalTodos);
        // TODO: Show user-friendly error notification
      } finally {
        setUpdatingTodoId(null); // Clear loading state
      }
    });
  };

  // --------Event handling Delete Todo and optimistic UI updates
  const handleDeleteTodo = async (todoId: string) => {
    // remove this and show better confirmation dialog or custom modal notification
    if (!window.confirm("Are you sure you want to delete this task?")) {
      return;
    }

    const originalTodos = todos; //storing the original state for potential revert
    setDeletingTodoId(todoId); // Set deleting state for visual feedback

    // 1. Optimistic UI update, immediately to update local state for the task to be deleted
    setTodos((prev) => prev.filter((todo) => todo.id !== todoId)); //  Remove immediately

    // calling server action and useTransition
    startTransition(async () => {
      try {
        // 2. Call 'deleteTask' server action
        const result = await deleteTask(todoId);

        // 3. Handle response from server action
        if (!result.success) {
          console.error("Failed to delete todo:", result.error);
          // Revert optimistic update on failure
          setTodos(originalTodos);
          // TODO: Show user-friendly error notification
        }
        // On success, the optimistic update is already applied
      } catch (error) {
        console.error("Error calling deleteTask:", error);
        // Revert optimistic update on unexpected error
        setTodos(originalTodos);
        // TODO: Show user-friendly error notification
      } finally {
        setDeletingTodoId(null); // Clear deleting state
      }
    });
  };

  // Derived state, to calculate a combined loading state based on individual loading flags
  //useful for disabling global actions like the main 'Add task' button
  const isLoading = isPending || !!updatingTodoId || !!deletingTodoId;

  return (
    <div className="container mx-auto p-4 max-w-4xl">
      <div className="mb-6">
        <div className="flex justify-between items-center mb-4">
          <h1 className="text-2xl font-bold text-gray-800">My Tasks</h1>
          {!isAddingTodo && (
            <button
              onClick={() => setIsAddingTodo(true)}
              className="flex items-center px-4 py-2 text-sm text-white bg-blue-500 rounded-lg hover:bg-blue-600 transition-colors disabled:opacity-50" // [cite: 84]
              disabled={isLoading} // Disable if any operation is pending
            >
              <PlusCircle size={18} className="mr-2" />
              Add Task
            </button>
          )}
        </div>

        {isAddingTodo && (
          <div className="relative  rounded-lg shadow-md p-4 border border-gray-200">
            <button
              onClick={() => setIsAddingTodo(false)}
              className="absolute top-2 right-2 text-gray-400 hover:text-gray-600 disabled:opacity-50"
              aria-label="Cancel adding task"
              disabled={isSubmittingForm} // Disable cancel only while form is actively submitting
            >
              <XCircle size={20} />
            </button>
            {/* Pass form submitting state to TodoForm */}
            <TodoForm // [cite: 86]
              onAddTodo={handleAddTodo}
              onCancel={() => setIsAddingTodo(false)}
              isSubmitting={isSubmittingForm} //  Use specific form state
            />
          </div>
        )}
      </div>

      {/* Loading indicator for background operations */}
      {isPending && (
        <div className="text-center text-gray-500 py-2">Processing...</div>
      )}

      {todos.length === 0 && !isPending ? (
        <div className="text-center py-10">
          <p className="text-gray-500">
            No tasks yet. Add a task to get started!
          </p>
        </div>
      ) : (
        <div className="grid gap-4 md:grid-cols-2 lg:grid-cols-3">
          {todos.map((todo) => (
            <TodoCard
              key={todo.id} // Use todo.id (temporary or real) as the key
              todo={todo} //task data iteself
              onUpdateTime={handleUpdateTime} //
              onEditTodo={handleEditTodo} //
              onDeleteTodo={handleDeleteTodo} //
              // Pass loading states to TodoCard
              isUpdating={updatingTodoId === todo.id}
              isDeleting={deletingTodoId === todo.id}
            />
          ))}
        </div>
      )}
    </div>
  );
}
